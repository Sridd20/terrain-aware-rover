"""
comparative_study.py
Comparative Study: MuJoCo Simulation vs Real Hardware Sensor Data

Generates a multi-panel figure showing side-by-side distributions and
scatter plots from both data sources, highlighting where simulation
matches reality and where it diverges.

Run:
    python comparative_study.py

Output:
    comparative_study.png   (main multi-panel figure)
    comparative_stats.csv   (per-terrain statistical summary)
"""

import matplotlib
matplotlib.use("Agg")

import glob
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import matplotlib.gridspec as gridspec
from matplotlib.patches import FancyBboxPatch
from scipy import stats

# ---------------------------------------------------------------------------
# Colour palette & terrain ordering
# ---------------------------------------------------------------------------
TERRAINS = ["tile", "pavement", "carpet", "gravel"]
COLORS   = {"tile": "#26BFFF", "pavement": "#33CC4D", "carpet": "#FFB31A", "gravel": "#E63333"}
MARKERS  = {"tile": "o", "pavement": "s", "carpet": "^", "gravel": "D"}
BG_DARK  = "#0F1117"
BG_PANEL = "#1A1D27"
GRID_CLR = "#2A2D3A"
SPINE_CLR= "#444455"

# ---------------------------------------------------------------------------
# 1. Load MuJoCo simulation data  (ml_dataset.csv — generated by generate_ml_dataset.py)
# ---------------------------------------------------------------------------
sim = pd.read_csv("ml_dataset.csv")
sim.columns = sim.columns.str.strip()
# Ensure 'label' is clean
sim["label"] = sim["label"].str.strip()
sim["source"] = "MuJoCo Sim"

# ---------------------------------------------------------------------------
# 2. Load real hardware data  (data/*.csv — collected from the physical rover)
# ---------------------------------------------------------------------------
hw_parts = []
for f in glob.glob("data/*.csv"):
    hw_parts.append(pd.read_csv(f))
hw = pd.concat(hw_parts, ignore_index=True)
hw.columns = hw.columns.str.strip()
hw["label"] = hw["label"].str.strip()

# Clean: drop idle / stale windows
idle  = hw["std"] < 0.02
hw    = hw[~idle]
stale = (hw.groupby("label")[["std", "p2p", "zcr"]].diff().abs().sum(axis=1) == 0)
hw    = hw[~stale].reset_index(drop=True)
hw["source"] = "Hardware"

# ---------------------------------------------------------------------------
# 3. Shared features for comparison
# ---------------------------------------------------------------------------
FEATURES = ["std", "rms", "p2p", "zcr"]
FEATURE_LABELS = {
    "std": "Vibration STD (m/s²)",
    "rms": "Vibration RMS (m/s²)",
    "p2p": "Peak-to-Peak (m/s²)",
    "zcr": "Zero-Crossing Rate",
}

# ---------------------------------------------------------------------------
# 4. Build the figure  (6 panels in a 3×2 grid)
# ---------------------------------------------------------------------------
fig = plt.figure(figsize=(20, 24), facecolor=BG_DARK)

# Main title
fig.suptitle(
    "Comparative Study: MuJoCo Simulation vs Real Hardware Data",
    color="white", fontsize=22, fontweight="bold", y=0.98,
)
fig.text(
    0.5, 0.965,
    "Terrain-Aware Rover  —  Vibration features extracted from accelerometer Z-axis",
    color="#AAAACC", fontsize=13, ha="center",
)

gs = gridspec.GridSpec(4, 2, hspace=0.35, wspace=0.30,
                       left=0.07, right=0.95, top=0.94, bottom=0.04)


def style_ax(ax, xlabel="", ylabel="", title=""):
    ax.set_facecolor(BG_PANEL)
    ax.set_xlabel(xlabel, color="white", fontsize=11)
    ax.set_ylabel(ylabel, color="white", fontsize=11)
    if title:
        ax.set_title(title, color="white", fontsize=13, fontweight="bold", pad=10)
    ax.tick_params(colors="white", labelsize=9)
    for spine in ax.spines.values():
        spine.set_edgecolor(SPINE_CLR)
    ax.grid(True, color=GRID_CLR, linestyle="--", linewidth=0.5, zorder=0)


# ===== Panel 1 & 2: Box plots — STD and P2P side-by-side for Sim vs HW =====
for col_idx, feat in enumerate(["std", "p2p"]):
    ax = fig.add_subplot(gs[0, col_idx])
    style_ax(ax, xlabel="Terrain", ylabel=FEATURE_LABELS[feat],
             title=f"{FEATURE_LABELS[feat]} — Sim vs Hardware")

    positions_sim = np.arange(len(TERRAINS)) * 3
    positions_hw  = positions_sim + 1

    sim_data = [sim[sim["label"] == t][feat].values for t in TERRAINS]
    hw_data  = [hw[hw["label"] == t][feat].values  for t in TERRAINS]

    bp_sim = ax.boxplot(
        sim_data, positions=positions_sim, widths=0.7, patch_artist=True,
        boxprops=dict(facecolor="#3A5FCD", alpha=0.7, edgecolor="white", linewidth=0.8),
        whiskerprops=dict(color="white", linewidth=0.8),
        capprops=dict(color="white", linewidth=0.8),
        medianprops=dict(color="#FFD700", linewidth=1.5),
        flierprops=dict(marker="o", markerfacecolor="#3A5FCD", markersize=3, alpha=0.5),
    )
    bp_hw = ax.boxplot(
        hw_data, positions=positions_hw, widths=0.7, patch_artist=True,
        boxprops=dict(facecolor="#FF6B6B", alpha=0.7, edgecolor="white", linewidth=0.8),
        whiskerprops=dict(color="white", linewidth=0.8),
        capprops=dict(color="white", linewidth=0.8),
        medianprops=dict(color="#FFD700", linewidth=1.5),
        flierprops=dict(marker="o", markerfacecolor="#FF6B6B", markersize=3, alpha=0.5),
    )

    ax.set_xticks(positions_sim + 0.5)
    ax.set_xticklabels([t.capitalize() for t in TERRAINS], color="white")
    ax.legend(
        [bp_sim["boxes"][0], bp_hw["boxes"][0]], ["MuJoCo Sim", "Hardware"],
        fontsize=9, facecolor=BG_PANEL, edgecolor=SPINE_CLR,
        labelcolor="white", loc="upper left",
    )


# ===== Panel 3 & 4: Scatter plots — STD vs ZCR for Sim and HW =====
for col_idx, (data, src_label) in enumerate([(sim, "MuJoCo Simulation"), (hw, "Hardware")]):
    ax = fig.add_subplot(gs[1, col_idx])
    style_ax(ax, xlabel="Vibration STD (m/s²)", ylabel="Zero-Crossing Rate",
             title=f"STD vs ZCR — {src_label}")
    for terrain in TERRAINS:
        pts = data[data["label"] == terrain]
        ax.scatter(
            pts["std"], pts["zcr"],
            c=COLORS[terrain], marker=MARKERS[terrain],
            s=70, alpha=0.80, edgecolors="white", linewidths=0.3,
            label=terrain.capitalize(), zorder=3,
        )
    legend = ax.legend(
        title="Terrain", title_fontsize=9, fontsize=8, framealpha=0.3,
        facecolor=BG_PANEL, edgecolor=SPINE_CLR, labelcolor="white",
    )
    legend.get_title().set_color("white")


# ===== Panel 5: Overlaid KDE — STD distribution for each terrain =====
ax = fig.add_subplot(gs[2, 0])
style_ax(ax, xlabel="Vibration STD (m/s²)", ylabel="Density",
         title="STD Distribution — Sim (solid) vs Hardware (dashed)")

for terrain in TERRAINS:
    sim_vals = sim[sim["label"] == terrain]["std"].values
    hw_vals  = hw[hw["label"]  == terrain]["std"].values

    if len(sim_vals) > 2:
        xs = np.linspace(0, max(sim_vals.max(), hw_vals.max()) * 1.2, 200)
        kde_sim = stats.gaussian_kde(sim_vals)
        ax.plot(xs, kde_sim(xs), color=COLORS[terrain], linewidth=2.0,
                label=f"{terrain.capitalize()} (Sim)")
    if len(hw_vals) > 2:
        xs = np.linspace(0, max(sim_vals.max(), hw_vals.max()) * 1.2, 200)
        kde_hw = stats.gaussian_kde(hw_vals)
        ax.plot(xs, kde_hw(xs), color=COLORS[terrain], linewidth=2.0,
                linestyle="--", label=f"{terrain.capitalize()} (HW)")

legend = ax.legend(fontsize=7, framealpha=0.3, ncol=2,
                   facecolor=BG_PANEL, edgecolor=SPINE_CLR, labelcolor="white")


# ===== Panel 6: Overlaid KDE — P2P distribution =====
ax = fig.add_subplot(gs[2, 1])
style_ax(ax, xlabel="Peak-to-Peak (m/s²)", ylabel="Density",
         title="P2P Distribution — Sim (solid) vs Hardware (dashed)")

for terrain in TERRAINS:
    sim_vals = sim[sim["label"] == terrain]["p2p"].values
    hw_vals  = hw[hw["label"]  == terrain]["p2p"].values

    if len(sim_vals) > 2:
        xs = np.linspace(0, max(sim_vals.max(), hw_vals.max()) * 1.2, 200)
        kde_sim = stats.gaussian_kde(sim_vals)
        ax.plot(xs, kde_sim(xs), color=COLORS[terrain], linewidth=2.0,
                label=f"{terrain.capitalize()} (Sim)")
    if len(hw_vals) > 2:
        xs = np.linspace(0, max(sim_vals.max(), hw_vals.max()) * 1.2, 200)
        kde_hw = stats.gaussian_kde(hw_vals)
        ax.plot(xs, kde_hw(xs), color=COLORS[terrain], linewidth=2.0,
                linestyle="--", label=f"{terrain.capitalize()} (HW)")

legend = ax.legend(fontsize=7, framealpha=0.3, ncol=2,
                   facecolor=BG_PANEL, edgecolor=SPINE_CLR, labelcolor="white")


# ===== Panel 7: Summary statistics bar chart — Mean STD per terrain =====
ax = fig.add_subplot(gs[3, 0])
style_ax(ax, xlabel="Terrain", ylabel="Mean Vibration STD (m/s²)",
         title="Mean STD per Terrain — Sim vs Hardware")

x_pos   = np.arange(len(TERRAINS))
width   = 0.35
sim_means = [sim[sim["label"] == t]["std"].mean() for t in TERRAINS]
hw_means  = [hw[hw["label"]  == t]["std"].mean() for t in TERRAINS]
sim_stds  = [sim[sim["label"] == t]["std"].std()  for t in TERRAINS]
hw_stds   = [hw[hw["label"]  == t]["std"].std()   for t in TERRAINS]

bars1 = ax.bar(x_pos - width/2, sim_means, width, yerr=sim_stds, capsize=4,
               color="#3A5FCD", alpha=0.8, edgecolor="white", linewidth=0.5,
               label="MuJoCo Sim", error_kw=dict(ecolor="white", lw=0.8))
bars2 = ax.bar(x_pos + width/2, hw_means, width, yerr=hw_stds, capsize=4,
               color="#FF6B6B", alpha=0.8, edgecolor="white", linewidth=0.5,
               label="Hardware", error_kw=dict(ecolor="white", lw=0.8))

ax.set_xticks(x_pos)
ax.set_xticklabels([t.capitalize() for t in TERRAINS], color="white")
ax.legend(fontsize=9, facecolor=BG_PANEL, edgecolor=SPINE_CLR, labelcolor="white")


# ===== Panel 8: Mean ZCR bar chart =====
ax = fig.add_subplot(gs[3, 1])
style_ax(ax, xlabel="Terrain", ylabel="Mean Zero-Crossing Rate",
         title="Mean ZCR per Terrain — Sim vs Hardware")

sim_means_zcr = [sim[sim["label"] == t]["zcr"].mean() for t in TERRAINS]
hw_means_zcr  = [hw[hw["label"]  == t]["zcr"].mean() for t in TERRAINS]
sim_stds_zcr  = [sim[sim["label"] == t]["zcr"].std()  for t in TERRAINS]
hw_stds_zcr   = [hw[hw["label"]  == t]["zcr"].std()   for t in TERRAINS]

bars1 = ax.bar(x_pos - width/2, sim_means_zcr, width, yerr=sim_stds_zcr, capsize=4,
               color="#3A5FCD", alpha=0.8, edgecolor="white", linewidth=0.5,
               label="MuJoCo Sim", error_kw=dict(ecolor="white", lw=0.8))
bars2 = ax.bar(x_pos + width/2, hw_means_zcr, width, yerr=hw_stds_zcr, capsize=4,
               color="#FF6B6B", alpha=0.8, edgecolor="white", linewidth=0.5,
               label="Hardware", error_kw=dict(ecolor="white", lw=0.8))

ax.set_xticks(x_pos)
ax.set_xticklabels([t.capitalize() for t in TERRAINS], color="white")
ax.legend(fontsize=9, facecolor=BG_PANEL, edgecolor=SPINE_CLR, labelcolor="white")


# ---------------------------------------------------------------------------
# Save figure
# ---------------------------------------------------------------------------
out_fig = "comparative_study.png"
fig.savefig(out_fig, dpi=180, bbox_inches="tight", facecolor=fig.get_facecolor())
print(f"Saved -> {out_fig}")

# ---------------------------------------------------------------------------
# 5. Generate comparative statistics CSV
# ---------------------------------------------------------------------------
stats_rows = []
for terrain in TERRAINS:
    sim_t = sim[sim["label"] == terrain]
    hw_t  = hw[hw["label"]  == terrain]
    for feat in FEATURES:
        s_vals = sim_t[feat].values
        h_vals = hw_t[feat].values
        # Welch's t-test for difference in means
        if len(s_vals) > 1 and len(h_vals) > 1:
            t_stat, p_val = stats.ttest_ind(s_vals, h_vals, equal_var=False)
        else:
            t_stat, p_val = float("nan"), float("nan")
        stats_rows.append({
            "terrain":       terrain,
            "feature":       feat,
            "sim_mean":      round(float(np.mean(s_vals)), 4),
            "sim_std":       round(float(np.std(s_vals)), 4),
            "sim_median":    round(float(np.median(s_vals)), 4),
            "sim_n":         len(s_vals),
            "hw_mean":       round(float(np.mean(h_vals)), 4),
            "hw_std":        round(float(np.std(h_vals)), 4),
            "hw_median":     round(float(np.median(h_vals)), 4),
            "hw_n":          len(h_vals),
            "mean_diff":     round(float(np.mean(h_vals) - np.mean(s_vals)), 4),
            "mean_ratio":    round(float(np.mean(h_vals) / np.mean(s_vals)) if np.mean(s_vals) != 0 else float("nan"), 4),
            "t_statistic":   round(t_stat, 4),
            "p_value":       round(p_val, 6),
            "significant":   "YES" if p_val < 0.05 else "NO",
        })

stats_df = pd.DataFrame(stats_rows)
out_csv = "comparative_stats.csv"
stats_df.to_csv(out_csv, index=False)
print(f"Saved -> {out_csv}")
print(f"\n{'='*70}")
print("COMPARATIVE SUMMARY")
print(f"{'='*70}")
print(f"  MuJoCo samples : {len(sim)} ({', '.join(f'{t}: {len(sim[sim.label==t])}' for t in TERRAINS)})")
print(f"  Hardware samples: {len(hw)} ({', '.join(f'{t}: {len(hw[hw.label==t])}' for t in TERRAINS)})")
print()

# Print key findings
print("Per-terrain feature comparison (mean ± std):")
print(f"{'Terrain':<12} {'Feature':<6} {'Sim Mean±Std':<20} {'HW Mean±Std':<20} {'Ratio':<8} {'Sig?':<5}")
print("-" * 75)
for _, row in stats_df.iterrows():
    print(f"{row['terrain']:<12} {row['feature']:<6} "
          f"{row['sim_mean']:>7.3f} ± {row['sim_std']:<7.3f}  "
          f"{row['hw_mean']:>7.3f} ± {row['hw_std']:<7.3f}  "
          f"{row['mean_ratio']:>6.2f}x  "
          f"{row['significant']:<5}")
